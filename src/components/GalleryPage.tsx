const ORIGINAL_SIZE = { w: 3260, h: 5800 };

// Grid tiles use small thumbs; the opened photo upgrades to the large copy
// (both generated by scripts/make-gallery-thumbs.sh)
const PHOTO_COUNT = 49;

// Which photo sits in each layout slot: a fixed shuffle so photos from the same
// shoot don't bunch up, seeded so the arrangement is the same on every visit
const SLOT_PHOTOS = (() => {
  const order = Array.from({ length: PHOTO_COUNT }, (_, i) => i);
  let seed = 7;
  const rand = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
})();
const THUMB_SOURCES = Array.from({ length: PHOTO_COUNT }, (_, i) => `/photo-final/thumb/${i + 1}.jpg`);
const LARGE_SOURCES = Array.from({ length: PHOTO_COUNT }, (_, i) => `/photo-final/large/${i + 1}.jpg`);

// Motion is tuned per 60fps frame and scaled by real elapsed time, so it runs at
// the same speed on 60Hz and 120Hz screens
const FRAME_MS = 1000 / 60;
// Ease factor per 60fps frame, adjusted for this frame's length
const easeFor = (perFrame: number, frames: number) => 1 - Math.pow(1 - perFrame, frames);

// Grid drift per 60fps frame (px), always in the same direction
const DRIFT = { x: 0.3, y: 0.15 };

// Touch fling: velocity kept per 60fps frame after release, and the speed (px/ms)
// below which it stops
const FLING_FRICTION = 0.95;
const FLING_MIN_SPEED = 0.01;
// Release speed is measured over this much of the end of the swipe
const FLING_SAMPLE_MS = 100;
// How closely the grid follows the finger per 60fps frame: about a frame behind,
// which smooths out touch updates that don't line up with screen refreshes
const TOUCH_FOLLOW = 0.6;

// Touch screens: the grid moves as one layer and tiles skip mouse parallax
const COARSE_POINTER = window.matchMedia('(pointer: coarse)').matches;
// Tiles further than this outside the screen are hidden so they aren't drawn
const OFFSCREEN_MARGIN = 300;

// Wrap a position into [-size/2, size/2) so the 2x2 grid repeats forever
const wrap = (v: number, size: number) => ((v + size / 2) % size + size) % size - size / 2;

// Large copies are fetched and decoded once, starting as early as hover
const largeLoads = new Map<number, Promise<void>>();
const loadLarge = (index: number) => {
  let load = largeLoads.get(index);
  if (!load) {
    const large = new Image();
    large.src = LARGE_SOURCES[index];
    load = large.decode().catch(() => {});
    largeLoads.set(index, load);
  }
  return load;
};

// Show a photo on a tile: the cached thumb until the large copy is decoded
const showLargePhoto = (img: HTMLImageElement, index: number) => {
  img.dataset.want = String(index);
  if (!img.src.endsWith(LARGE_SOURCES[index])) img.src = THUMB_SOURCES[index];
  loadLarge(index).then(() => {
    if (img.dataset.want === String(index)) img.src = LARGE_SOURCES[index];
  });
};

// Warm up the slideshow's next/previous photos once the current one is in,
// so they don't compete with it for bandwidth
const preloadNeighbours = (index: number) => {
  loadLarge(index).then(() => {
    loadLarge((index + 1) % PHOTO_COUNT);
    loadLarge((index - 1 + PHOTO_COUNT) % PHOTO_COUNT);
  });
};

// Resolve when the large copy is ready, or after maxWait so opening never stalls
const waitForLarge = (index: number, maxWait: number) =>
  Promise.race([loadLarge(index), new Promise<void>((resolve) => setTimeout(resolve, maxWait))]);

